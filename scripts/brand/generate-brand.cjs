const { wordPath } = require('./wordmark.cjs');
const fs = require('fs'), sharp = require('sharp');
const FONT = 'Outfit-Variable.ttf', W = 500, TRACK = .16;
const R = 'D:/Luma/LUMA/android/app/src/main/res/drawable/';
const B = 'D:/Luma/LUMA/scripts/brand/';
// Fit a word path into a box (centred), returning a transform string.
function place(wp, cx, cy) {
  return `translate(${(cx - wp.width / 2).toFixed(2)},${(cy - (wp.minY + wp.maxY) / 2).toFixed(2)})`;
}
// Vector drawables have no transforms on paths, so bake the translation in.
function bake(d, tx, ty) {
  return d.replace(/([MLHVCSQTAZ])([^MLHVCSQTAZ]*)/gi, (m, cmd, args) => {
    const n = args.trim() ? args.trim().split(/[\s,]+/).map(Number) : [];
    const C = cmd.toUpperCase();
    if (C === 'Z') return 'Z';
    if (C === 'H') return 'H' + n.map(v => (v + tx).toFixed(2)).join(' ');
    if (C === 'V') return 'V' + n.map(v => (v + ty).toFixed(2)).join(' ');
    return C + n.map((v, i) => (v + (i % 2 ? ty : tx)).toFixed(2)).join(' ');
  });
}
function build(kind, w, h, text, size) {
  const wp = wordPath(FONT, W, TRACK, text, size);
  const tx = w / 2 - wp.width / 2, ty = h / 2 - (wp.minY + wp.maxY) / 2;
  const d = bake(wp.d, tx, ty);
  const r = Math.max(w, h) * .6;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w * 3}" height="${h * 3}" viewBox="0 0 ${w} ${h}">
 <defs><radialGradient id="lift" cx="${w / 2}" cy="${h * .42}" r="${r}" gradientUnits="userSpaceOnUse">
  <stop offset="0" stop-color="#17171C"/><stop offset="1" stop-color="#050506"/></radialGradient></defs>
 <path fill="url(#lift)" d="M0,0h${w}v${h}h-${w}z"/>
 <path fill="#FFFFFF" d="${d}"/>
</svg>`;
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Luma ${kind}: white ${text === 'L' ? 'L monogram' : 'LUMA wordmark'} (Outfit 500, tracked) on deep black.
     Generated by scripts/brand/generate-brand.cjs; edit that, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="${w}dp" android:height="${h}dp"
    android:viewportWidth="${w}" android:viewportHeight="${h}">
 <path android:pathData="M0,0h${w}v${h}h-${w}z">
  <aapt:attr name="android:fillColor">
   <gradient android:type="radial" android:centerX="${w / 2}" android:centerY="${h * .42}" android:gradientRadius="${r}">
    <item android:offset="0" android:color="#FF17171C"/>
    <item android:offset="1" android:color="#FF050506"/>
   </gradient>
  </aapt:attr>
 </path>
 <path android:fillColor="#FFFFFFFF" android:pathData="${d}"/>
</vector>
`;
  return { svg, xml };
}
(async () => {
  const icon = build('icon', 108, 108, 'L', 56);
  const banner = build('banner', 320, 180, 'LUMA', 46);
  fs.writeFileSync(R + 'luma_icon.xml', icon.xml);
  fs.writeFileSync(R + 'luma_banner.xml', banner.xml);
  fs.writeFileSync(B + 'luma-icon.svg', icon.svg);
  fs.writeFileSync(B + 'luma-banner.svg', banner.svg);
  const i = await sharp(Buffer.from(icon.svg)).png().toBuffer();
  const b = await sharp(Buffer.from(banner.svg)).png().toBuffer();
  await sharp({ create: { width: 1440, height: 560, channels: 3, background: '#2a2d33' } })
    .composite([{ input: i, left: 40, top: 110 }, { input: b, left: 450, top: 10 }]).png().toFile('brand-preview2.png');
  console.log('ok');
})();
